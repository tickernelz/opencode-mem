import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const site = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repo = resolve(site, "..");
const source = resolve(repo, "web/src/app.css");

function block(css, selector) {
  const start = css.indexOf(`${selector} {`);
  if (start === -1) throw new Error(`web/src/app.css: missing "${selector}" token block`);
  const end = css.indexOf("}", start);
  const declarations = [...css.slice(start, end).matchAll(/--([a-z0-9-]+):\s*([^;]+);/g)];
  if (declarations.length === 0) throw new Error(`web/src/app.css: "${selector}" has no tokens`);
  return declarations.map(([, name, value]) => `  --om-${name}: ${value.trim()};`).join("\n");
}

const css = await readFile(source, "utf8");
const light = block(css, ":root");
const dark = block(css, ".dark");
// Default :root = dark (matches <html data-theme="dark">). Light only when explicitly set.
const out = [
  "/* generated by github-site/scripts/build-tokens.mjs from web/src/app.css */",
  `:root,\n:root[data-theme="dark"] {\n${dark}\n  color-scheme: dark;\n}`,
  `:root[data-theme="light"] {\n${light}\n  color-scheme: light;\n}`,
  "",
].join("\n");

await mkdir(resolve(site, "src/generated"), { recursive: true });
await writeFile(resolve(site, "src/generated/tokens.css"), out);
await mkdir(resolve(site, "public"), { recursive: true });
await copyFile(resolve(repo, "web/public/favicon.svg"), resolve(site, "public/favicon.svg"));
await copyFile(resolve(repo, "web/public/favicon.ico"), resolve(site, "public/favicon.ico"));
console.log("tokens: web/src/app.css -> src/generated/tokens.css");
